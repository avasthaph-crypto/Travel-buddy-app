/**
 * Generates or customizes a complete bespoke itinerary for any destination and profile
 */
export function generateCuratedItinerary(
  destination: Destination,
  profile: GuestProfile,
  durationDays: number = 3,
  startDate: string = new Date().toISOString().split('T')[0]
): Itinerary {
  const destId = destination.id.toLowerCase();
  const template = TEMPLATES[destId];

  let days: ItineraryDay[] = [];

  if (template) {
    for (let i = 0; i < durationDays; i++) {
      const templateDay = template.days[i % template.days.length];
      const clonedItems = templateDay.items.map((item) => ({
        ...item,
        id: `${item.id}-day${i + 1}`,
      }));
      const items = adjustActivityPacing(clonedItems, profile);
      days.push({
        dayNumber: i + 1,
        theme: templateDay.theme,
        summary: templateDay.summary,
        items,
        weatherAdvisory: 'Gentle morning light, warm midday sun, crisp twilight.',
      });
    }
  } else {
    days = buildDynamicFallbackDays(destination, profile, durationDays);
  }

  const syncCode = generateSyncCode();

  return {
    id: `itin-${destination.id}-${Date.now().toString(36)}`,
    tripTitle: template
      ? template.titleTemplate
      : `${destination.city} Unveiled: Bespoke Encounters & Haute Gastronomy`,
    destination,
    profile,
    durationDays,
    startDate,
    summary: template
      ? template.summaryTemplate
      : `An exquisite ${durationDays}-day curation designed for ${profile.name}, balancing iconic monuments, street food discoveries, and refined tables across ${destination.city}.`,
    conciergePreamble: template
      ? template.preamble
      : `Dear ${profile.name}, we are delighted to anticipate your stay in ${destination.city}. Every dining reservation, route transition, and hidden gem has been tailored to your ${profile.pace} travel rhythm and love for authentic discovery.`,
    culturalEtiquette: destination.culturalEtiquette,
    days,
    createdAt: new Date().toISOString(),
    syncCode,
    offlineReady: true,
  };
}
